#!/usr/bin/env node
// One plugin source -> every CLI's layout.
//
// Source of truth (Agent Plugins 1.0.0, https://agent-plugins.org):
//   plugin.json          $schema, name, version, description, author, homepage, repository,
//                        license, keywords, extensions{<client namespace>: {...}}
//   skills/<name>/SKILL.md
//   mcp.json             optional: {$schema, mcpServers: {id: {type: stdio|streamable-http|sse, ...}}}
//
// Read natively (nothing generated): Antigravity (agy), Codex skills, VS Code, Cursor,
// Copilot, Kiro and other Agent Plugins clients.
// Generated here, committed beside the source (marketplaces clone the repo; there is no
// build step at install time):
//   .claude-plugin/plugin.json, .claude-plugin/marketplace.json, .claude-plugin/mcp.json
//   .codex-plugin/plugin.json             (only the Codex store card: interface; Codex reads the rest natively)
//   gemini-extension.json
//   mcp_config.json                     (agy's native MCP file, only when mcp.json has servers)
//
// Usage: node tools/build-plugins.mjs [repoRoot] [--check]
//   --check  writes nothing; exits 1 when a generated file is missing or stale (for CI).
//
// Client-only data lives under plugin.json `extensions`, keyed by namespace:
//   "com.anthropic.claude-code": {marketplace: {...entry fields}, owner, plugin: {...extra plugin.json keys}}
//   "com.openai":                {interface: {...}, ...}   (Codex's own namespace; passed through)
//   "com.google.gemini-cli":     {contextFileName, excludeTools, ...}
//   "dev.toast":                 {marketplaceName}          (shared marketplace name; default = plugin name)

import fs from "node:fs";
import path from "node:path";

const SPEC = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json";
const NS = { claude: "com.anthropic.claude-code", codex: "com.openai", gemini: "com.google.gemini-cli", toast: "dev.toast" };
const GENERATED_NOTE = "generated by tools/build-plugins.mjs from plugin.json; edit the source";

const args = process.argv.slice(2);
const check = args.includes("--check");
const root = path.resolve(args.find((a) => !a.startsWith("--")) || ".");
const warnings = [];
const warn = (m) => warnings.push(m);

const readJson = (rel, optional = false) => {
  const p = path.join(root, rel);
  if (!fs.existsSync(p)) {
    if (optional) return null;
    throw new Error(`${rel} not found in ${root}`);
  }
  return JSON.parse(fs.readFileSync(p, "utf8"));
};

// ---------------------------------------------------------------- source
const src = readJson("plugin.json");
if (src.$schema !== SPEC) throw new Error(`plugin.json $schema must be ${SPEC}`);
if (!/^(?!.*(?:--|\.\.))[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/.test(src.name || "")) throw new Error("plugin.json name: lowercase, digits, . and -");
const ext = src.extensions && typeof src.extensions === "object" ? src.extensions : {};
const exClaude = ext[NS.claude] || {};
const exCodex = ext[NS.codex] || {};
const exGemini = ext[NS.gemini] || {};
const exToast = ext[NS.toast] || {};
const market = exToast.marketplaceName || src.name;

const skillsDir = path.join(root, "skills");
const skills = fs.existsSync(skillsDir)
  ? fs.readdirSync(skillsDir).filter((d) => fs.existsSync(path.join(skillsDir, d, "SKILL.md"))).sort()
  : [];
for (const s of skills) {
  const head = fs.readFileSync(path.join(skillsDir, s, "SKILL.md"), "utf8").slice(0, 2000);
  const name = /^---[\s\S]*?^name:\s*["']?([^"'\n]+)/m.exec(head)?.[1]?.trim();
  if (name !== s) warn(`skills/${s}/SKILL.md: frontmatter name "${name}" differs from its folder (Agent Skills requires a match)`);
  // agy 1.5.9, measured (agy-skill-limit.md): an explicit /<skill> load keeps the first 24,000 bytes
  // of the body after the frontmatter and drops the rest behind "<truncated N bytes>". A skill the
  // agent picks from its list is read with read_file instead, which pages at 46,080 bytes and can
  // read on. Codex 0.164.0 loads a 60 KB SKILL.md whole.
  const raw = fs.readFileSync(path.join(skillsDir, s, "SKILL.md"));
  const text = raw.toString("utf8");
  const close = text.startsWith("---") ? text.indexOf("\n---", 3) : -1;
  const fmEnd = close < 0 ? 0 : text.indexOf("\n", close + 4) + 1 || text.length;
  const body = raw.length - Buffer.byteLength(text.slice(0, fmEnd));
  if (body > 24000) warn(`skills/${s}/SKILL.md body is ${body} bytes; agy's /${s} load keeps only the first 24000 (the rest is cut)`);
}

const mcpSrc = readJson("mcp.json", true);
const servers = mcpSrc?.mcpServers || {};

// The common metadata every manifest repeats.
const meta = {};
for (const k of ["name", "version", "description", "author", "homepage", "repository", "license", "keywords"]) {
  if (src[k] !== undefined) meta[k] = src[k];
}

// ---------------------------------------------------------------- MCP dialects
// Agent Plugins placeholders: ${PLUGIN_ROOT}, ${PLUGIN_DATA} in args, env values and cwd.
const subst = (value, map) =>
  typeof value === "string" ? value.replace(/\$\{(PLUGIN_ROOT|PLUGIN_DATA)\}/g, (m, k) => (k in map ? map[k] : m)) : value;
const substAll = (obj, map) => (Array.isArray(obj) ? obj.map((v) => subst(v, map)) : obj && typeof obj === "object"
  ? Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, subst(v, map)])) : subst(obj, map));

function claudeServer(id, s) {
  // Claude Code: ${CLAUDE_PLUGIN_ROOT}; ${CLAUDE_PLUGIN_DATA} is the persistent data dir.
  const map = { PLUGIN_ROOT: "${CLAUDE_PLUGIN_ROOT}", PLUGIN_DATA: "${CLAUDE_PLUGIN_DATA}" };
  if (s.type === "stdio") {
    const out = { type: "stdio", command: s.command.startsWith("./") ? "${CLAUDE_PLUGIN_ROOT}/" + s.command.slice(2) : s.command };
    if (s.args) out.args = substAll(s.args, map);
    if (s.env) out.env = substAll(s.env, map);
    if (s.cwd) out.cwd = subst(s.cwd, map);
    return out;
  }
  if (s.type === "streamable-http" || s.type === "sse") {
    return { type: s.type === "sse" ? "sse" : "http", url: s.url, ...(s.headers ? { headers: s.headers } : {}) };
  }
  warn(`mcp.json ${id}: unknown type ${s.type}; skipped for Claude`);
  return null;
}

function geminiServer(id, s) {
  // Gemini CLI extension: ${extensionPath}; httpUrl = streamable HTTP, url = SSE.
  const map = { PLUGIN_ROOT: "${extensionPath}" };
  if (s.type === "stdio") {
    const out = { command: s.command.startsWith("./") ? "${extensionPath}/" + s.command.slice(2) : s.command };
    if (s.args) out.args = substAll(s.args, map);
    if (s.env) out.env = substAll(s.env, map);
    out.cwd = s.cwd ? subst(s.cwd, map) : "${extensionPath}";
    if (JSON.stringify(out).includes("${PLUGIN_DATA}")) warn(`mcp.json ${id}: Gemini has no PLUGIN_DATA; left literal`);
    return out;
  }
  if (s.type === "streamable-http") return { httpUrl: s.url, ...(s.headers ? { headers: s.headers } : {}) };
  if (s.type === "sse") return { url: s.url, ...(s.headers ? { headers: s.headers } : {}) };
  return null;
}

function agyServer(id, s) {
  // Antigravity native mcp_config.json (read while enable-agent-plugins-spec is off; agy
  // expands ${PLUGIN_ROOT} / ${PLUGIN_DATA} itself). stdio: command, args, env (no cwd).
  // Remote: url (Streamable HTTP only; legacy SSE unsupported).
  if (s.type === "stdio") {
    const out = { command: s.command.startsWith("./") ? "${PLUGIN_ROOT}/" + s.command.slice(2) : s.command };
    if (s.args) out.args = s.args;
    if (s.env) out.env = s.env;
    if (s.cwd) warn(`mcp.json ${id}: agy's mcp_config.json has no cwd; dropped there`);
    return out;
  }
  if (s.type === "streamable-http") return { url: s.url, ...(s.headers ? { headers: s.headers } : {}) };
  warn(`mcp.json ${id}: agy has no ${s.type} transport; skipped for agy (and agy validate --strict fails on it in mcp.json)`);
  return null;
}

const mapServers = (fn) => {
  const out = {};
  for (const [id, s] of Object.entries(servers)) {
    const m = fn(id, s);
    if (m) out[id] = m;
  }
  return out;
};

// ---------------------------------------------------------------- outputs
const files = {};
const hasMcp = Object.keys(servers).length > 0;

// Claude Code
const claudeMcp = hasMcp ? mapServers(claudeServer) : {};
files[".claude-plugin/plugin.json"] = {
  ...meta,
  ...(Object.keys(claudeMcp).length ? { mcpServers: "./.claude-plugin/mcp.json" } : {}),
  ...(exClaude.plugin || {}),
};
if (Object.keys(claudeMcp).length) files[".claude-plugin/mcp.json"] = { mcpServers: claudeMcp };
const owner = exClaude.owner || (src.author ? { name: src.author.name, ...(src.author.email ? { email: src.author.email } : {}) } : { name: src.name });
files[".claude-plugin/marketplace.json"] = {
  name: market,
  description: exClaude.marketplaceDescription || src.description,
  owner,
  plugins: [{
    name: src.name,
    source: "./",
    description: src.description,
    ...(src.version ? { version: src.version } : {}),
    ...(src.author ? { author: src.author } : {}),
    ...(src.homepage ? { homepage: src.homepage } : {}),
    ...(src.license ? { license: src.license } : {}),
    ...(exClaude.marketplace || {}),
  }],
};

// Codex reads the Agent Plugins source natively (plugin.json, skills/, mcp.json with
// ${PLUGIN_ROOT}/${PLUGIN_DATA} expanded) and finds the plugin through
// .claude-plugin/marketplace.json, so no Codex MCP file or Codex marketplace is generated.
// Verified with codex-cli 0.164: when both exist, the root mcp.json wins over a
// .codex-plugin mcpServers pointer. The Codex manifest below only carries the store card.
const { interface: codexInterface, ...codexRest } = exCodex;
if (codexInterface || Object.keys(codexRest).length) {
  files[".codex-plugin/plugin.json"] = {
    ...meta,
    ...(skills.length ? { skills: "./skills/" } : {}),
    ...(codexInterface ? { interface: codexInterface } : {}),
    ...(Object.keys(codexRest).length ? { extensions: { [NS.codex]: codexRest } } : {}),
  };
}

// Antigravity: reads plugin.json + skills/ natively; MCP needs its own mcp_config.json until
// its enable-agent-plugins-spec flag is on by default.
const agyMcp = hasMcp ? mapServers(agyServer) : {};
if (Object.keys(agyMcp).length) files["mcp_config.json"] = { mcpServers: agyMcp };

// Gemini CLI extension
if (exGemini.contextFileName && !fs.existsSync(path.join(root, exGemini.contextFileName)))
  warn(`gemini contextFileName ${exGemini.contextFileName} does not exist`);
const geminiMcp = hasMcp ? mapServers(geminiServer) : {};
files["gemini-extension.json"] = {
  name: src.name,
  ...(src.version ? { version: src.version } : {}),
  ...(src.description ? { description: src.description } : {}),
  ...(Object.keys(geminiMcp).length ? { mcpServers: geminiMcp } : {}),
  ...exGemini,
};

// ---------------------------------------------------------------- write / check
let stale = 0;
for (const [rel, data] of Object.entries(files)) {
  const text = JSON.stringify(data, null, 2) + "\n";
  const p = path.join(root, rel);
  const old = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
  if (old === text) continue;
  stale++;
  if (check) { console.log(`stale: ${rel}`); continue; }
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, text);
  console.log(`wrote: ${rel}`);
}
// Stray generated MCP files from an earlier build with servers.
for (const rel of [".claude-plugin/mcp.json", ".codex-plugin/mcp.json", ".agents/plugins/marketplace.json", "mcp_config.json"]) {
  if (!(rel in files) && fs.existsSync(path.join(root, rel))) {
    stale++;
    if (check) console.log(`stale: ${rel} (no servers now)`);
    else { fs.rmSync(path.join(root, rel)); console.log(`removed: ${rel}`); }
  }
}
for (const w of warnings) console.log(`warning: ${w}`);
console.log(`${src.name}: ${skills.length} skill(s), ${Object.keys(servers).length} MCP server(s); ${stale ? (check ? stale + " stale" : stale + " written") : "up to date"}  (${GENERATED_NOTE})`);
process.exit(check && stale ? 1 : 0);
